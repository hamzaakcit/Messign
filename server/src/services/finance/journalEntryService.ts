import { query, getClient } from '../../db/index.js';
import { auditService } from './auditService.js';

export const journalEntryService = {
  async generateFromExpense(expenseId: string, event: 'approved' | 'paid') {
    const exp = await query(
      `SELECT r.*, ec.gl_code, r.organization_id
       FROM reimbursement_requests r
       LEFT JOIN expense_categories ec ON ec.id = r.category_id
       WHERE r.id = $1`,
      [expenseId],
    );
    if (!exp.rows[0]) return null;
    const e = exp.rows[0];
    const orgId = e.organization_id;
    const amount = parseFloat(e.amount);
    const period = (event === 'approved' ? e.approved_at : e.paid_at)?.slice(0, 7)
      || new Date().toISOString().slice(0, 7);

    const expenseGLCode = e.gl_code || '6000';
    const sourceType = event === 'approved' ? 'expense_approved' : 'expense_paid';

    let drCode: string, crCode: string, description: string;
    if (event === 'approved') {
      drCode = expenseGLCode;
      crCode = '2000';
      description = `Expense approved: ${e.title}`;
    } else {
      drCode = '2000';
      crCode = '1000';
      description = `Expense payment: ${e.title}`;
    }

    return this._createEntry(orgId, {
      description,
      source_type: sourceType,
      source_id: expenseId,
      period,
      entry_date: new Date().toISOString().split('T')[0],
      lines: [
        { gl_code: drCode, debit: amount, credit: 0, description },
        { gl_code: crCode, debit: 0, credit: amount, description },
      ],
    });
  },

  async generateFromInvoice(invoiceId: string, event: 'sent' | 'paid', paymentAmount?: number) {
    const inv = await query(
      `SELECT * FROM invoices WHERE id = $1`,
      [invoiceId],
    );
    if (!inv.rows[0]) return null;
    const i = inv.rows[0];
    const orgId = i.organization_id;
    const amount = paymentAmount ?? parseFloat(i.grand_total || i.total_amount);
    const period = new Date().toISOString().slice(0, 7);

    let drCode: string, crCode: string, description: string, sourceType: string;
    if (event === 'sent') {
      drCode = '1100';
      crCode = '4000';
      description = `Invoice sent: ${i.invoice_number} to ${i.to_name}`;
      sourceType = 'invoice_sent';
    } else {
      drCode = '1000';
      crCode = '1100';
      description = `Invoice payment received: ${i.invoice_number}`;
      sourceType = 'invoice_paid';
    }

    return this._createEntry(orgId, {
      description,
      source_type: sourceType,
      source_id: invoiceId,
      period,
      entry_date: new Date().toISOString().split('T')[0],
      lines: [
        { gl_code: drCode, debit: amount, credit: 0, description },
        { gl_code: crCode, debit: 0, credit: amount, description },
      ],
    });
  },

  async generateFromPayment(paymentId: string) {
    const p = await query(`SELECT * FROM finance_payments WHERE id = $1`, [paymentId]);
    if (!p.rows[0]) return null;
    const pay = p.rows[0];
    const orgId = pay.organization_id;
    const amount = parseFloat(pay.amount);
    const period = new Date().toISOString().slice(0, 7);

    return this._createEntry(orgId, {
      description: `Payment completed: ${pay.payment_number}`,
      source_type: 'payment_completed',
      source_id: paymentId,
      period,
      entry_date: new Date().toISOString().split('T')[0],
      lines: [
        { gl_code: '2000', debit: amount, credit: 0, description: `Payment ${pay.payment_number}` },
        { gl_code: '1000', debit: 0, credit: amount, description: `Payment ${pay.payment_number}` },
      ],
    });
  },

  async _createEntry(orgId: string, data: {
    description: string;
    source_type: string;
    source_id: string;
    period: string;
    entry_date: string;
    lines: Array<{ gl_code: string; debit: number; credit: number; description: string }>;
    created_by?: string;
  }) {
    const client = await getClient();
    try {
      await client.query('BEGIN');

      const existing = await client.query(
        `SELECT id FROM finance_journal_entries WHERE source_type = $1 AND source_id = $2 AND organization_id = $3 AND status != 'voided'`,
        [data.source_type, data.source_id, orgId],
      );
      if (existing.rows.length > 0) {
        await client.query('ROLLBACK');
        return existing.rows[0];
      }

      const numResult = await client.query(
        `SELECT COALESCE(MAX(CAST(NULLIF(REGEXP_REPLACE(entry_number, '[^0-9]', '', 'g'), '') AS INTEGER)), 0) + 1 AS next_num
         FROM finance_journal_entries WHERE organization_id = $1`,
        [orgId],
      );
      const entryNumber = `JE-${String(numResult.rows[0]?.next_num ?? 1).padStart(5, '0')}`;

      const totalDebit = data.lines.reduce((s, l) => s + l.debit, 0);
      const totalCredit = data.lines.reduce((s, l) => s + l.credit, 0);

      const isAutoGenerated = data.source_type !== 'manual';
      const entry = await client.query(
        `INSERT INTO finance_journal_entries
         (organization_id, entry_number, entry_date, description, source_type, source_id,
          status, period, total_debit, total_credit, is_auto_generated, posted_at, created_by)
         VALUES ($1,$2,$3,$4,$5,$6,'posted',$7,$8,$9,$10,NOW(),$11)
         RETURNING *`,
        [orgId, entryNumber, data.entry_date, data.description, data.source_type,
         data.source_id, data.period, totalDebit, totalCredit, isAutoGenerated, data.created_by || null],
      );

      for (let i = 0; i < data.lines.length; i++) {
        const line = data.lines[i];
        const glAccount = await client.query(
          `SELECT id FROM finance_gl_accounts WHERE organization_id = $1 AND code = $2`,
          [orgId, line.gl_code],
        );
        if (!glAccount.rows[0]) {
          console.warn(`[journal] GL account ${line.gl_code} not found for org ${orgId}, skipping line`);
          continue;
        }
        await client.query(
          `INSERT INTO finance_journal_lines (journal_entry_id, gl_account_id, debit_amount, credit_amount, description, sort_order)
           VALUES ($1,$2,$3,$4,$5,$6)`,
          [entry.rows[0].id, glAccount.rows[0].id, line.debit, line.credit, line.description, i],
        );
      }

      await client.query('COMMIT');

      auditService.log({
        organization_id: orgId,
        event_type: 'journal_entry.created',
        event_category: 'accounting',
        actor_type: data.created_by ? 'user' : 'system',
        actor_id: data.created_by || 'system',
        entity_type: 'journal_entry',
        entity_id: entry.rows[0].id,
        changes: { source_type: data.source_type, total: totalDebit },
      }).catch((err) => console.error('[journalEntryService] auditService.log failed', { error: err instanceof Error ? err.message : String(err) }));

      return entry.rows[0];
    } catch (e) {
      await client.query('ROLLBACK');
      throw e;
    } finally {
      client.release();
    }
  },

  async list(orgId: string, filters: { period?: string; source_type?: string; status?: string; search?: string; limit?: number; offset?: number } = {}) {
    const conditions = ['je.organization_id = $1'];
    const params: unknown[] = [orgId];
    let idx = 2;

    if (filters.period) { conditions.push(`je.period = $${idx++}`); params.push(filters.period); }
    if (filters.source_type) { conditions.push(`je.source_type = $${idx++}`); params.push(filters.source_type); }
    if (filters.status) { conditions.push(`je.status = $${idx++}`); params.push(filters.status); }
    if (filters.search) { conditions.push(`(je.description ILIKE $${idx} OR je.entry_number ILIKE $${idx})`); params.push(`%${filters.search}%`); idx++; }

    const limit = filters.limit ?? 50;
    const offset = filters.offset ?? 0;

    const result = await query(
      `SELECT je.*,
         (SELECT json_agg(json_build_object(
           'id', jl.id, 'gl_account_id', jl.gl_account_id,
           'debit_amount', jl.debit_amount, 'credit_amount', jl.credit_amount,
           'description', jl.description, 'sort_order', jl.sort_order,
           'gl_code', g.code, 'gl_name', g.name
         ) ORDER BY jl.sort_order)
         FROM finance_journal_lines jl
         JOIN finance_gl_accounts g ON g.id = jl.gl_account_id
         WHERE jl.journal_entry_id = je.id) AS lines
       FROM finance_journal_entries je
       WHERE ${conditions.join(' AND ')}
       ORDER BY je.entry_date DESC, je.created_at DESC
       LIMIT $${idx++} OFFSET $${idx++}`,
      [...params, limit, offset],
    );

    const countResult = await query(
      `SELECT COUNT(*) FROM finance_journal_entries je WHERE ${conditions.join(' AND ')}`,
      params,
    );

    return { entries: result.rows, total: parseInt(countResult.rows[0].count) };
  },

  async getById(orgId: string, id: string) {
    const result = await query(
      `SELECT je.*,
         (SELECT json_agg(json_build_object(
           'id', jl.id, 'gl_account_id', jl.gl_account_id,
           'debit_amount', jl.debit_amount, 'credit_amount', jl.credit_amount,
           'description', jl.description, 'sort_order', jl.sort_order,
           'gl_code', g.code, 'gl_name', g.name
         ) ORDER BY jl.sort_order)
         FROM finance_journal_lines jl
         JOIN finance_gl_accounts g ON g.id = jl.gl_account_id
         WHERE jl.journal_entry_id = je.id) AS lines
       FROM finance_journal_entries je
       WHERE je.id = $1 AND je.organization_id = $2`,
      [id, orgId],
    );
    return result.rows[0] ?? null;
  },

  async void_(orgId: string, id: string, userId: string) {
    const entry = await this.getById(orgId, id);
    if (!entry) throw new Error('Journal entry not found');
    if (entry.status !== 'posted') throw new Error('Only posted entries can be voided');

    const client = await getClient();
    try {
      await client.query('BEGIN');

      await client.query(
        `UPDATE finance_journal_entries SET status = 'voided' WHERE id = $1`,
        [id],
      );

      const numResult = await client.query(
        `SELECT COALESCE(MAX(CAST(NULLIF(REGEXP_REPLACE(entry_number, '[^0-9]', '', 'g'), '') AS INTEGER)), 0) + 1 AS next_num
         FROM finance_journal_entries WHERE organization_id = $1`,
        [orgId],
      );
      const entryNumber = `JE-${String(numResult.rows[0]?.next_num ?? 1).padStart(5, '0')}`;

      const reversal = await client.query(
        `INSERT INTO finance_journal_entries
         (organization_id, entry_number, entry_date, description, source_type, source_id,
          status, period, total_debit, total_credit, is_auto_generated, posted_at, created_by, notes)
         VALUES ($1,$2,CURRENT_DATE,$3,'void_reversal',$4,'posted',$5,$6,$7,FALSE,NOW(),$8,$9)
         RETURNING *`,
        [orgId, entryNumber, `Void reversal of ${entry.entry_number}: ${entry.description}`,
         id, entry.period, entry.total_credit, entry.total_debit, userId,
         `Reversing entry for ${entry.entry_number}`],
      );

      if (entry.lines) {
        for (const line of entry.lines) {
          await client.query(
            `INSERT INTO finance_journal_lines (journal_entry_id, gl_account_id, debit_amount, credit_amount, description, sort_order)
             VALUES ($1,$2,$3,$4,$5,$6)`,
            [reversal.rows[0].id, line.gl_account_id, parseFloat(line.credit_amount), parseFloat(line.debit_amount),
             `Reversal: ${line.description || ''}`, line.sort_order],
          );
        }
      }

      await client.query('COMMIT');

      auditService.log({
        organization_id: orgId,
        event_type: 'journal_entry.voided',
        event_category: 'accounting',
        actor_type: 'user',
        actor_id: userId,
        entity_type: 'journal_entry',
        entity_id: id,
        changes: { reversal_id: reversal.rows[0].id },
      }).catch((err) => console.error('[journalEntryService] auditService.log failed', { error: err instanceof Error ? err.message : String(err) }));

      return reversal.rows[0];
    } catch (e) {
      await client.query('ROLLBACK');
      throw e;
    } finally {
      client.release();
    }
  },
};
