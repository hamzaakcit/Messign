import { useEffect, useMemo, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { doraBriefingAPI, type DailyBriefing } from '@/lib/api';
import { useAuthStore } from '@/stores/authStore';
import { useDailyBriefingStore } from '@/stores/dailyBriefingStore';

function fmtDate(dateIso: string): string {
  return new Date(`${dateIso}T12:00:00`).toLocaleDateString(undefined, {
    weekday: 'long',
    month: 'long',
    day: 'numeric',
    year: 'numeric',
  });
}

function fmtTime(iso: string): string {
  return new Date(iso).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
}

export function DailyBriefingPage() {
  const navigate = useNavigate();
  const user = useAuthStore((s) => s.user);
  const userId = user?.authUserId || user?.id || '';
  const dateKey = useMemo(() => new Date().toISOString().slice(0, 10), []);
  const cached = useDailyBriefingStore((s) => s.getBriefing(userId, dateKey));
  const setBriefing = useDailyBriefingStore((s) => s.setBriefing);
  const [briefing, setLocalBriefing] = useState<DailyBriefing | null>(cached);
  const [loading, setLoading] = useState(!cached);
  const [expanded, setExpanded] = useState<Record<string, boolean>>({});
  const [refreshing, setRefreshing] = useState(false);

  useEffect(() => {
    if (cached) {
      setLocalBriefing(cached);
      setLoading(false);
    }
  }, [cached]);

  const hydrateExpansion = (b: DailyBriefing) => {
    const next: Record<string, boolean> = {};
    for (const section of b.sections) {
      next[section.module] = section.priority === 'high';
    }
    setExpanded(next);
  };

  useEffect(() => {
    if (!userId) return;
    if (cached) {
      hydrateExpansion(cached);
      return;
    }
    let cancelled = false;
    setLoading(true);
    doraBriefingAPI.getToday(userId)
      .then((res) => {
        if (cancelled) return;
        setLocalBriefing(res);
        setBriefing(userId, res);
        hydrateExpansion(res);
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });
    return () => { cancelled = true; };
  }, [userId, dateKey, cached, setBriefing]);

  const refresh = async () => {
    if (!userId) return;
    setRefreshing(true);
    try {
      const fresh = await doraBriefingAPI.getToday(userId, true);
      setLocalBriefing(fresh);
      setBriefing(userId, fresh);
      hydrateExpansion(fresh);
    } finally {
      setRefreshing(false);
    }
  };

  if (loading || !briefing) {
    return <div className="p-6 text-app-muted">Generating today&apos;s briefing...</div>;
  }

  return (
    <div className="h-[calc(100vh-64px)] overflow-y-auto p-4 md:p-6 bg-app space-y-4">
      <div className="rounded-xl border border-app bg-app-card p-5">
        <h1 className="text-2xl font-bold text-app">{briefing.greeting}</h1>
        <p className="text-sm text-app-muted mt-1">{fmtDate(briefing.date)} · ✦ Generated by Dora</p>
      </div>

      <div className="rounded-xl border border-indigo-500/30 bg-gradient-to-r from-indigo-700/30 to-blue-700/20 p-5">
        <p className="text-base md:text-lg text-indigo-100">{briefing.summary}</p>
      </div>

      <div className="space-y-3">
        {briefing.sections.map((section) => (
          <div
            key={section.module}
            className={`rounded-lg border bg-app-card ${
              section.priority === 'high' ? 'border-amber-500/50 border-l-4' : 'border-app'
            }`}
          >
            <button
              className="w-full text-left px-4 py-3 flex items-center justify-between"
              onClick={() => setExpanded((prev) => ({ ...prev, [section.module]: !prev[section.module] }))}
            >
              <div className="text-app font-medium">
                <span className="mr-2">{section.icon}</span>
                {section.title}
              </div>
              <div className="text-xs text-app-muted">{section.items.length} items</div>
            </button>
            {expanded[section.module] && (
              <div className="px-4 pb-4 space-y-2">
                {section.items.map((item, idx) => (
                  <div key={`${section.module}-${idx}`} className="rounded border border-app bg-app p-3 flex items-start justify-between gap-3">
                    <div>
                      <div className="text-sm text-app flex items-center gap-2">
                        <span
                          className={`h-2 w-2 rounded-full ${
                            item.severity === 'critical' ? 'bg-red-500' :
                            item.severity === 'warning' ? 'bg-amber-500' :
                            item.severity === 'success' ? 'bg-emerald-500' : 'bg-blue-500'
                          }`}
                        />
                        {item.text}
                      </div>
                    </div>
                    {item.actionUrl && (
                      <button
                        className="text-xs text-cyan-300 hover:text-cyan-200 whitespace-nowrap"
                        onClick={() => navigate(item.actionUrl!)}
                      >
                        {item.actionLabel || 'Open'}
                      </button>
                    )}
                  </div>
                ))}
              </div>
            )}
          </div>
        ))}
      </div>

      <div className="rounded-lg border border-app bg-app-card p-4 flex items-center justify-between">
        <div className="text-xs text-app-muted">
          Powered by Dora — this briefing was generated at {fmtTime(briefing.generatedAt)}
        </div>
        <button
          className="text-xs px-3 py-1.5 rounded border border-app text-app hover:bg-app-hover"
          onClick={refresh}
          disabled={refreshing}
        >
          {refreshing ? 'Refreshing...' : 'Refresh'}
        </button>
      </div>
    </div>
  );
}
